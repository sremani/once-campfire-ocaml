#!/usr/bin/env python3
"""Pin the Rust port's Rails-verified Propshaft output for the OCaml server.

Run `cargo test -p campfire_assets --test reference` in the sibling Rust checkout
first. That suite checks the generated bytes against the pinned Rails reference.
This exporter copies the compiled payloads and metadata; Python is only needed
when refreshing assets, never to build or run the OCaml application.
"""

import json
import re
import shutil
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RUST = ROOT.parent / "once-campfire-rust"
EXPECTED_RUST = "9872c1d9541551c0889a60e3d49a14488bd1e403"
EXPECTED_RAILS = "90b330024dec3e757c79b6a7e6568f93da8e3148"
for directory, expected in [(RUST, EXPECTED_RUST), (RUST / "reference", EXPECTED_RAILS)]:
    actual = subprocess.check_output(["git", "-C", str(directory), "rev-parse", "HEAD"], text=True).strip()
    if actual != expected:
        raise SystemExit(f"{directory} is {actual}, expected {expected}")
generated = list((RUST / "target/debug/build").glob("campfire_assets-*/out/embedded.rs"))
if len(generated) != 1:
    raise SystemExit(f"expected one generated asset file, got {generated}")
code = generated[0].read_text()
destination = ROOT / "assets"
files = destination / "files"
if files.exists():
    shutil.rmtree(files)
files.mkdir(parents=True, exist_ok=True)

sources = {}
for ident, path in re.findall(r"static (ASSET_\d+|PUBLIC_\d+): &\[u8\] = include_bytes!\((\".*?\")\);", code):
    sources[ident] = Path(json.loads(path))

for url, ident in re.findall(r'^    \((".*?"), (ASSET_\d+|PUBLIC_\d+|MANIFEST_JSON\.as_bytes\(\))\),$', code, re.M):
    url = json.loads(url)
    output = files / url.lstrip("/")
    output.parent.mkdir(parents=True, exist_ok=True)
    if ident != "MANIFEST_JSON.as_bytes()":
        shutil.copyfile(sources[ident], output)

for name, output in [
    ("MANIFEST_JSON", destination / "manifest.json"),
    ("IMPORTMAP_TAGS", destination / "javascript_importmap_tags.html"),
    ("BUILT_AT", destination / "built_at.txt"),
]:
    match = re.search(rf'^pub\(crate\) static {name}: &str = (".*");$', code, re.M)
    if not match:
        raise SystemExit(f"missing {name}")
    output.write_text(json.loads(match.group(1)))

shutil.copyfile(destination / "manifest.json", files / "assets/.manifest.json")
fixture_target = ROOT / "test/fixtures/assets"
shutil.copytree(RUST / "crates/assets/tests/reference", fixture_target, dirs_exist_ok=True)
print(f"exported {len(list(p for p in files.rglob('*') if p.is_file()))} files from {generated[0]}")
